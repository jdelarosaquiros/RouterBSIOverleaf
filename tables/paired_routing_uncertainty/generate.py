#!/usr/bin/env python3
"""Regenerate this table from its frozen local CSV; no raw evaluation runs."""
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASELINES = ['SkillSight', 'LLM Select', 'SkillRouter', 'SkillDAG', 'Skill-Pro']
METRICS = ['nDCG@1', 'nDCG@10', 'MRR@10']
SUMMARIES = [('run_1', 'Primary: RouterBSI run 1'),
             ('three_run_task_mean', 'Sensitivity: per-task mean of three fixed RouterBSI systems')]

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    binding = json.loads((HERE/'input_binding.json').read_text())
    assert sha(HERE/'results.csv') == binding['results_csv_sha256']
    rows = list(csv.DictReader((HERE/'results.csv').open()))
    assert len(rows) == 210
    chosen = [r for r in rows if r['dataset']=='Overall']
    bykey = {(r['summary'], r['baseline'], r['metric']): r for r in chosen}
    assert len(bykey) == len(chosen) == 30
    assert set(bykey) == {(s,b,k) for s,_ in SUMMARIES for b in BASELINES for k in METRICS}
    caption = (HERE/'description.text').read_text().strip()
    lines = [r'% Generated by generate.py from frozen results.csv.',
             r'\begin{table*}[t]', r'\centering', r'\small',
             r'\setlength{\tabcolsep}{3pt}',
             r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lccc@{}}',
             r'\toprule',r'Baseline & $\Delta$ nDCG@1 & $\Delta$ nDCG@10 & $\Delta$ MRR@10 \\',r'\midrule']
    selected = []
    for s,title in SUMMARIES:
        if selected:
            lines.append(r'\midrule')
        lines.extend([r'\multicolumn{4}{l}{\textit{'+title+r'}} \\',r'\midrule'])
        for baseline in BASELINES:
            cells=[]
            for metric in METRICS:
                r=bykey[s,baseline,metric]
                assert int(r['n_tasks']) == 748 and int(r['n_clusters']) == 747
                values=[float(r[k])*100 for k in ('difference','ci_low','ci_high')]
                assert values[1] <= values[2]
                cells.append(f'${values[0]:+.2f}$ [{values[1]:.2f}, {values[2]:.2f}]')
                selected.append(r)
            lines.append(' & '.join([baseline]+cells)+r' \\')
    lines.extend([r'\bottomrule',r'\end{tabular*}',r'\caption{'+caption+'}',
                  r'\label{tab:paired-routing-uncertainty}',r'\end{table*}'])
    (HERE/'table.tex').write_text('\n'.join(lines)+'\n')
    manifest={'artifact':'paired_routing_uncertainty','analysis_status':'analysis_only',
              'reportability_upgraded':False,'source_binding':binding,
              'selected_rows':selected,'rows_displayed':10,'metric_cells':30,
              'display_units':'100 times score difference; percentage points, not relative percent',
              'format':'two decimal places; pointwise 95% percentile intervals',
              'generator_sha256':sha(Path(__file__)),
              'output_hashes':{n:sha(HERE/n) for n in ['table.tex','description.text','results.csv','provenance.text','preview.pdf','preview.png'] if (HERE/n).exists()}}
    (HERE/'selection_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Generated 10 rows / 30 verified metric cells; source CSV unchanged.')

if __name__=='__main__':
    main()
