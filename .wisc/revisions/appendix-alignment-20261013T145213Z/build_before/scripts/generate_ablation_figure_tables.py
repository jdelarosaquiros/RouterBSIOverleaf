#!/usr/bin/env python3
"""Generate only the appendix trajectory table; --check validates all ablation figures.

Uses frozen figure selections, never runs an experiment or rewrites a figure.
Source metric Hit@1 equals displayed nDCG@1 for the documented binary,
nonempty-gold tasks. Preserve the source's analysis-only/non-reportable status.
"""
import argparse
import csv
import hashlib
import json
import math
from pathlib import Path
import re

PAPER = Path(__file__).resolve().parents[1]
TRAJECTORY = "mbr_replay_test_ndcg@1_std"
BACKBONES = "routing_performance_across_llms_init"
TOKENS = "performance_token_usage"
METHODS = ("Both Disabled", "Only Gate", "Only MBR", "Both Enabled")
OUTPUT = PAPER / "sections/appendix/trajectory_table.tex"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(path):
    with path.open(newline="") as stream:
        return list(csv.DictReader(stream))


def selection(name, count):
    folder = PAPER / "figs" / name
    manifest = json.loads((folder / "selection_manifest.json").read_text())
    selected = folder / "selected_data.csv"
    rows = read_csv(selected)
    require(len(rows) == manifest["selected_row_count"] == count, name + ": row count")
    if isinstance(manifest["source"], str):
        source = PAPER.parent / manifest["source"]
        source_hash = manifest["source_sha256"]
        selected_hash = manifest["output_sha256"]["selected_data.csv"]
    else:
        source = PAPER.parent / manifest["source"]["path"]
        source_hash = manifest["source"]["sha256"]
        selected_hash = next(item["sha256"] for item in manifest["outputs"]
                             if item["path"].endswith("/selected_data.csv"))
    require(digest(selected) == selected_hash, name + ": frozen selection hash")
    require(digest(source) == source_hash, name + ": authoritative source hash")
    source_rows = read_csv(source)
    require(len(source_rows) == manifest["source_row_count"], name + ": source count")
    for row in rows:
        if "source_csv_row" in row:
            match = source_rows[int(row["source_csv_row"]) - 2]
            require(all(row[k] == match[k] for k in row if k in match),
                    name + ": source row mismatch")
        else:
            require(row in source_rows, name + ": selected row absent from source")
    return rows, manifest


def trajectory_table():
    rows, manifest = selection(TRAJECTORY, 44)
    require(len(manifest["points"]) == 44, "trajectory: frozen point count")
    keyed = {}
    for row, point in zip(rows, manifest["points"]):
        require(all(str(point[k]) == v for k, v in row.items()),
                "trajectory: frozen point mismatch")
        x = int(row["x"])
        require(row["Method"] in METHODS and 0 <= x <= 10, "trajectory: axes")
        require(all(row[k] == v for k, v in manifest["filters"].items()),
                "trajectory: selection filters")
        require(row["n_runs"] == "3" and row["n_tasks"] == "748", "trajectory: population")
        require(row["Iteration"] == ("initial" if x == 0 else str(x)), "trajectory: checkpoint")
        require(row["Evaluation"] == ("snapshot" if x == 0 else "accepted"),
                "trajectory: evaluation phase")
        sd = math.sqrt(float(row["Hit@1_variance"]))
        require(sd == float(row["Hit1_std"]), "trajectory: frozen population SD")
        key = (x, row["Method"])
        require(key not in keyed, "trajectory: duplicate point")
        keyed[key] = (float(row["Hit@1_mean"]), sd)
    require(set(keyed) == {(i, method) for i in range(11) for method in METHODS},
            "trajectory: incomplete grid")
    lines = [
        "% Generated by scripts/generate_ablation_figure_tables.py; do not edit cells.",
        r"\begin{table*}[t]", r"\centering", r"\small",
        r"\begin{tabular}{lrrrr}", r"\toprule",
        r"Iteration & Both Disabled & Only Gate & Only MBR & Both Enabled \\", r"\midrule",
    ]
    for i in range(11):
        cells = [r"\shortstack{" + f"{keyed[i, method][0]:.3f}" + r"\\{\scriptsize ("
                 + f"{keyed[i, method][1]:.3f}" + r")}}" for method in METHODS]
        lines.append(str(i) + " & " + " & ".join(cells) + r" \\")
    lines.extend([
        r"\bottomrule", r"\end{tabular}",
        r"\caption{Test nDCG@1 at initialization and each accepted iteration, averaged over three runs. Parentheses below each mean give population standard deviation across runs, reconstructed from variances rounded to six decimal places as in the plotted bands. These values expand the trajectory and uncertainty bands in Figure~\ref{fig:mbr_replay_test_ndcg@1_std}; they are not validation scores.}",
        r"\label{tab:app-ablation-trajectory}", r"\end{table*}", "",
    ])
    return "\n".join(lines)


def table_rows(path, width):
    result = []
    for line in path.read_text().splitlines():
        if " & " not in line or not line.endswith(r"\\"):
            continue
        cells = [cell.strip() for cell in line[:-2].split("&")]
        require(len(cells) == width, str(path) + ": row width")
        result.append([re.sub(r"\\(?:textbf|underline)\{([^{}]+)\}", r"\1", cell)
                       for cell in cells])
    return result


def check_existing_tables():
    rows, manifest = selection(BACKBONES, 7)
    require(len(manifest["points"]) == 7, "backbone: point count")
    table = table_rows(PAPER / "sections/appendix/ablation_backbones.tex", 5)[1:]
    require(len(table) == 7, "backbone: seven data rows")
    for i, (row, point, cells) in enumerate(zip(rows, manifest["points"], table)):
        require(all(row[k] == point[k] for k in ("Model", "Retriever", "Method", "Dataset")),
                "backbone: frozen identity")
        require(point["x"] == i and point["y"] == float(row["Hit@1"]), "backbone: frozen point")
        expected_label = ["SkillSight", "Reference"] if i == 0 else [
            row["Model"], "Initial" if row["Method"] == "RouterBSI_init" else "Final"]
        require(cells[:2] == expected_label, "backbone: row label/order")
        require(cells[2:] == [f"{float(row[k]):.3f}" for k in ("F1", "Hit@1", "nDCG@10")],
                "backbone: numeric cells")
    rows, manifest = selection(TOKENS, 4)
    require(len(manifest["points"]) == 4, "tokens: point count")
    table = table_rows(PAPER / "sections/appendix/ablation_cost_capacity.tex", 6)[1:5]
    require([row[0] for row in table] == list(METHODS), "tokens: method order")
    keyed = {row[0]: row for row in table}
    for row, point in zip(rows, manifest["points"]):
        require(all(row[k] == point[k] for k in ("Model", "Retriever", "Method")),
                "tokens: frozen identity")
        require(point["y"] == float(row["Hit@1"]) and
                point["x"] == int(row["Total Tokens"]) / 1_000_000, "tokens: frozen x/y")
        cells = keyed[row["Method"]]
        require(cells[2:4] == [f"{point['y']:.3f}", f"{point['x']:.3f}"], "tokens: table x/y")
    for file, name in (("ablation_backbones.tex", BACKBONES), ("ablation_cost_capacity.tex", TOKENS)):
        require(r"\ref{fig:" + name + "}" in (PAPER / "sections/appendix" / file).read_text(),
                name + ": caption figure reference")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Read-only source-level validation")
    args = parser.parse_args()
    expected = trajectory_table()
    if args.check:
        require(OUTPUT.read_text() == expected, "trajectory: generated table is stale")
        check_existing_tables()
        print("PASS: 44 trajectory means + population SDs; 7 backbone rows; 4 token x/y pairs; frozen selections and authoritative sources match.")
    else:
        OUTPUT.write_text(expected)
        print("Wrote sections/appendix/trajectory_table.tex (44 means + population SDs).")


if __name__ == "__main__":
    main()
